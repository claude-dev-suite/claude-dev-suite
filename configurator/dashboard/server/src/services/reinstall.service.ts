/**
 * Reinstall Service (erase-and-replace)
 *
 * Transactional reinstall/sync for existing dev-suite installations.
 *
 * Strategy: scoped erase + replace.
 *  - The manifest (`.dev-suite-manifest.json`) is the source of truth for what
 *    dev-suite OWNS on disk; `.dev-suite.json` is the source of truth for what
 *    to reinstall (the selection).
 *  - Only manifest-tracked MANAGED files are erased (agents, mcp-server dirs,
 *    rule files). Skills are cleaned + rebuilt by `install()` itself
 *    (`cleanStaleSkills`). Shared files (`CLAUDE.md`, `.claude/settings.json`,
 *    `.mcp.json`) are merged/regenerated by `install()` — never hard-erased.
 *  - User-owned content (`.claude/agents/custom/`, `.claude/skills/custom/`,
 *    files not in the manifest) is never touched.
 *  - Locally modified managed files are surfaced in preview; the user opts out
 *    per file (`keep`) to preserve their edits.
 *  - The whole erase+replace is wrapped in backup + rollback-on-error.
 *
 * This intentionally does NOT reuse `InstallationService.uninstall()`: that
 * removes dev-suite entirely, including the shared substrate a reinstall needs
 * to keep. (It used to be unsafe as well — a recursive delete of
 * `.claude/agents` and `.claude/skills` that took `custom/` with it — which
 * `installation/uninstall.ts` now fixes.)
 */

